-- 3. Subscriptions: one per customer. The ID modulo a number spreads them out:
--   plans:  30% Home 10, 30% Home 30, 20% Home 50, 10% Fiber 100, 5% each for the two biggest
--   status: 1 in 25 cancelled on 30 June 2026, the rest active
--   start:  somewhere in the first 300 days of 2025
INSERT INTO dbo.Subscriptions (CustomerID, PlanID, StartDate, EndDate, Status)
SELECT c.CustomerID,
       CASE WHEN c.CustomerID % 20 < 6  THEN 1
            WHEN c.CustomerID % 20 < 12 THEN 2
            WHEN c.CustomerID % 20 < 16 THEN 3
            WHEN c.CustomerID % 20 < 18 THEN 4
            WHEN c.CustomerID % 20 = 18 THEN 5
            ELSE 6 END,
       DATEADD(DAY, c.CustomerID % 300, CAST('2025-01-01' AS DATE)),
       CASE WHEN c.CustomerID % 25 = 0 THEN '2026-06-30' END,     -- NULL for the others
       CASE WHEN c.CustomerID % 25 = 0 THEN 'Cancelled'
            ELSE 'Active' END
FROM dbo.Customers AS c;
GO

-- 4. UsageRecords (the big table): one row per subscription per day,
-- from 2025-11-01 to 2026-10-31.
-- sys.all_objects is just a handy table with more than 365 rows, so
-- ROW_NUMBER can count the days.
--
-- To make the numbers look realistic:
--   - an average day is the plan's quota / 30
--   - each subscription has its own habit, (2 + ID % 10) / 10 = 0.2 to 1.1
--     of the quota, so some customers go over every month
--   - each day is a random 50% to 150% of that habit
--   - upload is about a tenth of that
WITH Calendar AS (
    SELECT TOP (365)
           DATEADD(DAY, ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) - 1, CAST('2025-11-01' AS DATE)) AS UsageDate
    FROM sys.all_objects
)
INSERT INTO dbo.UsageRecords (SubscriptionID, UsageDate, DownloadMB, UploadMB)
SELECT s.SubscriptionID,
       d.UsageDate,
       CAST(p.QuotaGB * 1024.0 / 30
            * ((2 + s.SubscriptionID % 10) / 10.0)
            * (0.5 + (ABS(CHECKSUM(NEWID())) % 1000) / 1000.0) AS INT),
       CAST(p.QuotaGB * 1024.0 / 30
            * 0.1
            * (0.5 + (ABS(CHECKSUM(NEWID())) % 1000) / 1000.0) AS INT)
FROM dbo.Subscriptions AS s
JOIN dbo.Plans AS p ON p.PlanID = s.PlanID
CROSS JOIN Calendar AS d
WHERE d.UsageDate >= s.StartDate
  AND (s.EndDate IS NULL OR d.UsageDate <= s.EndDate);     -- no usage after cancelling
GO

-- 5. Invoices: generated by our own billing procedure, one month at a time,
-- November 2025 to September 2026. October 2026 is left for the live demo.
DECLARE @MonthStart DATE = '2025-11-01';
DECLARE @y INT, @m INT;

WHILE @MonthStart <= '2026-09-01'
BEGIN
    SET @y = YEAR(@MonthStart);
    SET @m = MONTH(@MonthStart);

    EXEC dbo.usp_GenerateMonthlyInvoices @Year = @y, @Month = @m;

    SET @MonthStart = DATEADD(MONTH, 1, @MonthStart);
END;
GO

-- 6. Payments:
--   - everything up to August 2026 is paid in full
--   - September 2026: 4 out of 5 paid in full, 1 in 10 half paid, 1 in 10 unpaid
-- The payments and the invoice updates go in one transaction.
BEGIN TRANSACTION;

    -- full payments, 1 to 9 days after the end of the month
    INSERT INTO dbo.Payments (InvoiceID, Amount, Method, PaidAt)
    SELECT InvoiceID,
           Amount,
           CHOOSE(InvoiceID % 3 + 1, 'Cash', 'Card', 'Transfer'),
           DATEADD(DAY, 1 + InvoiceID % 9, PeriodEnd)
    FROM dbo.Invoices
    WHERE PeriodStart < '2026-09-01'
       OR SubscriptionID % 5 <> 0;

    UPDATE dbo.Invoices
    SET AmountPaid = Amount,
        Status     = 'Paid'
    WHERE PeriodStart < '2026-09-01'
       OR SubscriptionID % 5 <> 0;

    -- half payments on some September invoices
    INSERT INTO dbo.Payments (InvoiceID, Amount, Method, PaidAt)
    SELECT InvoiceID, ROUND(Amount / 2, 2), 'Cash', DATEADD(DAY, 5, PeriodEnd)
    FROM dbo.Invoices
    WHERE PeriodStart = '2026-09-01'
      AND SubscriptionID % 10 = 0;

    UPDATE dbo.Invoices
    SET AmountPaid = ROUND(Amount / 2, 2),
        Status     = 'Partial'
    WHERE PeriodStart = '2026-09-01'
      AND SubscriptionID % 10 = 0;

COMMIT TRANSACTION;
GO

